async def seed_textbook_mappings(db):
    """注入种子数据到 textbook_mappings 表"""
    subject_map = {"数学": "math", "语文": "chinese", "英语": "english",
                   "物理": "physics", "化学": "chemistry", "生物": "biology",
                   "历史": "history", "地理": "geography", "政治": "politics"}
    count = 0
    for subject_name, textbooks in TEXTBOOK_MAPPING_SEED.items():
        subject_id = subject_map.get(subject_name, subject_name.lower())
        for textbook_name, chapters in textbooks.items():
            for entry in chapters:
                chapter_code, chapter_name, section_code, section_name, kp_code, kp_name, weight = entry
                await db.execute(
                    """INSERT OR IGNORE INTO textbook_mappings
                       (subject_id, textbook_name, chapter_code, chapter_name,
                        section_code, section_name, kp_code, kp_name, weight)
                       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                    (subject_id, textbook_name, chapter_code, chapter_name,
                     section_code, section_name, kp_code, kp_name, weight),
                )
                count += 1
    await db.commit()
    print(f"✅ 已注入 {count} 条教材映射种子数据")
    return count


